# Example second backend — OpenAI, initialized differently,
# formats/parses differently, but honors the same contract.
# ============================================================
class ChatOpenAILLM(LLMSelection):

    def __init__(self, prompt_provider: Prompt, history: ConversationHistory):
        from langchain_openai import ChatOpenAI

        self._prompt_provider = prompt_provider
        self._history = history
        self._llm = ChatOpenAI(
            model=os.getenv("OPENAI_MODEL"),
            api_key=os.getenv("OPENAI_API_KEY"),
            temperature=float(os.getenv("OPENAI_TEMPERATURE", "0.7")),
        )

    async def sendMessagestollm(self, session_id: str, userInput: str) -> LLMResponse:
        prompt = self._build_prompt(session_id, userInput)
        dynamic_headers = {
            "X-Request-ID": str(uuid.uuid4())
        }
        raw = await self._llm.ainvoke(prompt, headers=dynamic_headers)
        logger.info(f"Raw response from OpenAI LLM: {raw}")
        response = self._parse_response(raw)

        self._history.append(session_id, [
            HumanMessage(content=userInput),
            AIMessage(content=response.output),
        ])
        return response

    def _build_prompt(self, session_id: str, userInput: str) -> str:
        past = self._history.get(session_id)
        history_text = "\n".join(
            f"{'User' if isinstance(m, HumanMessage) else 'Assistant'}: {m.content}"
            for m in past
        )
        return f"{self._prompt_provider.systemprompt()}\n\n{history_text}\n\nUser: {userInput}"

    def _parse_response(self, raw) -> LLMResponse:
        return LLMResponse(output=raw.content)

    def rawllm(self):
        return self._llm
    
    def structuredllm(self):
        return self._llm.with_structured_output(LLMResponseLanggraph)
    
    async def close(self) -> None:
        pass


# ============================================================
# Factory — the only place that knows which concrete class to build (OCP)
# ============================================================
class LLMFactory:
    _registry: dict[str, type[LLMSelection]] = {
        "bedrock": ChatBedrockLLM,
        "bedrock_mantle": ChatBedrockOpenAILLM,
        "openai": ChatOpenAILLM,
    }

    @classmethod
    def create(cls, provider: str, prompt_provider: Prompt, history: ConversationHistory) -> LLMSelection:
        try:
            llm_cls = cls._registry[provider]
        except KeyError:
            raise ValueError(f"Unknown LLM provider: {provider}")
        return llm_cls(prompt_provider=prompt_provider, history=history)

    @classmethod
    def register(cls, name: str, llm_cls: type[LLMSelection]) -> None:
        """Lets new LLMs be plugged in without editing this file (true OCP)."""
        cls._registry[name] = llm_cls