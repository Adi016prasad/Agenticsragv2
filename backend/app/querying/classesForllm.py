    def _format_messagesForFiltering(self, parenttext: list[str], userInput: str) -> list:
        return [
            SystemMessage(content=self._prompt_provider.filteringsystemprompt(parenttext)),
            HumanMessage(content=userInput),
        ]

    def _parse_response(self, raw) -> LLMResponse:
        return LLMResponse(output=raw.content)

    def rawllm(self):
        return self._llm

    def structuredllm(self):
        return self._llm.with_structured_output(LLMResponseLanggraph, method="json_schema")

    async def close(self) -> None:
        pass

